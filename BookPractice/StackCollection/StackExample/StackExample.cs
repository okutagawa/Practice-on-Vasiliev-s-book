using System;
using System.Collections.Generic;

namespace BookPractice
{
    public class StackExample
    {
        static void Main()
        {
            // Стек (Stack) — это структура данных, работающая по принципу LIFO
            // (Last In, First Out — последний зашел, первый вышел).
            // Аналогия: стопка тарелок. Кладешь сверху — берешь тоже сверху.

            // ---------------------------------------------
            // 1. СОЗДАНИЕ СТЕКА
            // ---------------------------------------------
            // Стандартное объявление пустого стека
            Stack<int> numbers = new Stack<int>();

            // Можно создать стек и сразу заполнить его значениями
            // ВАЖНО: порядок в стеке будет обратный порядку перечисления!
            // То есть первым наверх ляжет "четыре", а не "один".
            Stack<string> words = new Stack<string>();
            words.Push("один");
            words.Push("два");
            words.Push("три");
            words.Push("четыре");

            // ---------------------------------------------
            // 2. ДОБАВЛЕНИЕ ЭЛЕМЕНТОВ (Push)
            // ---------------------------------------------
            // Push — кладет элемент НАВЕРХ стека
            numbers.Push(1); // низ
            numbers.Push(2);
            numbers.Push(3);
            numbers.Push(4); // верх
            // Внутри стек выглядит так: [1, 2, 3, 4] (4 - наверху)

            // ---------------------------------------------
            // 3. ПРОСМОТР ВЕРХНЕГО ЭЛЕМЕНТА (Peek)
            // ---------------------------------------------
            // Peek — смотрит на верхний элемент, НЕ удаляя его
            Console.WriteLine("Верхний элемент стека numbers: " + numbers.Peek()); // Выведет 4

            // ---------------------------------------------
            // 4. ИЗВЛЕЧЕНИЕ ЭЛЕМЕНТА (Pop)
            // ---------------------------------------------
            // Pop — снимает верхний элемент и возвращает его
            int top = numbers.Pop();
            Console.WriteLine("Сняли со стека: " + top); // Выведет 4
            // Теперь верхний элемент — 3

            // ---------------------------------------------
            // 5. ПРОВЕРКА НАЛИЧИЯ И РАЗМЕР
            // ---------------------------------------------
            Console.WriteLine("Есть ли число 2 в стеке? " + numbers.Contains(2)); // true
            Console.WriteLine("Сколько элементов в стеке? " + numbers.Count);    // 3

            // ---------------------------------------------
            // 6. ПЕРЕБОР ЭЛЕМЕНТОВ СТЕКА
            // ---------------------------------------------
            // Цикл foreach по стеку проходит от ВЕРХА к НИЗУ (от последнего к первому)
            Console.WriteLine("\nПеребор стека (от верха к низу):");
            foreach (int n in numbers)
            {
                Console.WriteLine(n); // Сначала выведет 3, потом 2, потом 1
            }

            // ---------------------------------------------
            // 7. ПОЛНОЕ ИЗВЛЕЧЕНИЕ ЧЕРЕЗ ЦИКЛ (Классический способ)
            // ---------------------------------------------
            Console.WriteLine("\nИзвлекаем все элементы:");
            while (numbers.Count > 0)
            {
                int item = numbers.Pop();
                Console.WriteLine("Сняли: " + item);
            }
            // Вывод: 3, 2, 1 — обрати внимание на обратный порядок

            // ---------------------------------------------
            // 8. БЕЗОПАСНОЕ ИЗВЛЕЧЕНИЕ (TryPop)
            // ---------------------------------------------
            // TryPop — не вызовет ошибку, если стек пуст.
            // Вернет true, если снял элемент, и false, если стек был пуст.
            if (numbers.TryPop(out int result))
            {
                Console.WriteLine("Сняли: " + result);
            }
            else
            {
                Console.WriteLine("Стек пуст, снимать нечего!");
            }

            // ---------------------------------------------
            // 9. ОЧИСТКА СТЕКА (Clear)
            // ---------------------------------------------
            words.Clear();
            Console.WriteLine("\nПосле очистки слов в стеке: " + words.Count); // 0

            // ---------------------------------------------
            // 10. ПРАКТИЧЕСКИЙ ПРИМЕР: РАЗВОРОТ СТРОКИ
            // ---------------------------------------------
            // Стек — идеальный инструмент для разворота данных
            string text = "Привет, мир!";
            Stack<char> letters = new Stack<char>();

            // Кладем каждую букву в стек
            foreach (char c in text)
            {
                letters.Push(c);
            }

            // Собираем обратно, снимая со стека
            string reversed = "";
            while (letters.Count > 0)
            {
                reversed += letters.Pop();
            }

            Console.WriteLine("\nОригинал: " + text);
            Console.WriteLine("Развернуто: " + reversed); // !рим ,тевирП

            // ---------------------------------------------
            // ИТОГ: КОГДА ИСПОЛЬЗОВАТЬ СТЕК?
            // ---------------------------------------------
            // 1. Когда важен ПОРЯДОК, обратный порядку добавления (LIFO).
            // 2. История действий (Undo/Redo, кнопка "Назад" в браузере).
            // 3. Разворот данных (строк, массивов).
            // 4. Алгоритмы обхода (DFS — поиск в глубину).
            // 5. Рекурсия (внутри себя C# использует стек вызовов).

            // Помни: главное отличие от Queue — там FIFO (первый зашел, первый вышел),
            // а в стеке LIFO (последний зашел, первый вышел).
        }
    }
}